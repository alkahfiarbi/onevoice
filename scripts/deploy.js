// Deploy script for OneVoice on BSC mainnet.
//
// SAFETY: by default this script ONLY estimates the deploy cost and prints it.
// It broadcasts NOTHING. Pass --broadcast to actually deploy (parent runs it
// after the user signs in with the Binance Agentic Wallet).
//
// Usage (dry run / estimate only):
//   npx hardhat run scripts/deploy.js --network bsc
// Usage (real deploy):
//   DEPLOYER_PRIVATE_KEY=0x... npx hardhat run scripts/deploy.js --network bsc --broadcast
//
// NOTE: the deployer key must NEVER be committed or printed. It is read from
// the environment only. In production the parent deploys via `baw`
// (Binance Agentic Wallet) instead of a raw key where possible.
const { ethers, network } = require("hardhat");
const fs = require("fs");
const path = require("path");

const AGENT_ID = "0x60b9262456de011f7d15a54cdd8c48baaa8b022f";
const USER_BALANCE_BNB = "0.000434"; // user's wallet balance, for the affordability check

async function main() {
  const broadcast = process.argv.includes("--broadcast");
  console.log(`Network: ${network.name} | mode: ${broadcast ? "BROADCAST" : "ESTIMATE ONLY"}`);

  const factory = await ethers.getContractFactory("OneVoice");
  const deployTx = await factory.getDeployTransaction(AGENT_ID);
  // Estimate from the user's wallet (estimation only — no signature needed).
  deployTx.from = "0xfBcE2E2D17F7C89CaA567B50Cd5f98570F7fFd5D";
  const provider = ethers.provider;

  const gasPrice = await provider.getFeeData().then((f) => f.gasPrice);
  const gasLimit = await provider.estimateGas(deployTx);
  const costWei = gasLimit * gasPrice;
  const costBnb = ethers.formatEther(costWei);
  console.log(`Gas price (live): ${ethers.formatUnits(gasPrice, "gwei")} gwei`);
  console.log(`Estimated deploy gas: ${gasLimit.toString()}`);
  console.log(`Estimated deploy cost: ${costBnb} BNB`);
  console.log(`User wallet balance: ${USER_BALANCE_BNB} BNB`);
  const fits = BigInt(costWei) <= ethers.parseEther(USER_BALANCE_BNB);
  console.log(`Fits in balance: ${fits ? "YES" : "NO"}`);
  if (!fits) {
    console.log("STOP: deploy does not fit the wallet balance. Do not broadcast.");
    return;
  }

  if (!broadcast) {
    console.log("Dry run done — nothing broadcast. Re-run with --broadcast to deploy.");
    return;
  }

  const pk = process.env.DEPLOYER_PRIVATE_KEY;
  if (!pk) {
    throw new Error("DEPLOYER_PRIVATE_KEY env var is required for --broadcast");
  }
  const deployer = new ethers.Wallet(pk, provider);
  console.log(`Deployer: ${deployer.address}`);
  const balance = await provider.getBalance(deployer.address);
  console.log(`Deployer balance: ${ethers.formatEther(balance)} BNB`);
  if (balance < costWei) throw new Error("Deployer balance below deploy cost");

  const factoryWithSigner = factory.connect(deployer);
  const contract = await factoryWithSigner.deploy(AGENT_ID);
  console.log(`Deploy tx sent: ${contract.deploymentTransaction().hash}`);
  await contract.waitForDeployment();
  const address = await contract.getAddress();
  console.log(`OneVoice deployed at: ${address}`);

  // Save deployment info + wire the frontend config.
  const outDir = path.join(__dirname, "..", "deployments");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, "bsc.json"),
    JSON.stringify({ network: "bsc", chainId: 56, address, agentId: AGENT_ID, deployTx: contract.deploymentTransaction().hash }, null, 2)
  );
  const configPath = path.join(__dirname, "..", "frontend", "config.js");
  const docsConfigPath = path.join(__dirname, "..", "docs", "config.js");
  const configContent =
    `// Auto-generated by scripts/deploy.js — do not edit by hand.\nwindow.ONEVOICE = {\n  address: "${address}",\n  chainId: 56,\n  agentId: "${AGENT_ID}"\n};\n`;
  fs.writeFileSync(configPath, configContent);
  fs.writeFileSync(docsConfigPath, configContent);
  console.log(`Deployment saved to deployments/bsc.json; frontend config updated.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
